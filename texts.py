def _load():
    if not os.path.exists(HISTORY_FILE):
        return {}
    try:
        with open(HISTORY_FILE, 'r', encoding='utf-8') as f:
            return json.load(f)
    except Exception:
        return {}


def _save(data):
    try:
        with open(HISTORY_FILE, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False)
    except Exception:
        pass


def next_text(kind):
    # Ek-i text bar bar ashbe na: sob combination shesh hole tabei abar shuru hobe
    a, b, c = POOLS[kind]
    with _lock:
        data = _load()
        used = set(data.get(kind, []))
        free = []
        for i in range(len(a)):
            for j in range(len(b)):
                for k in range(len(c)):
                    key = str(i) + '-' + str(j) + '-' + str(k)
                    if key not in used:
                        free.append((i, j, k, key))
        if not free:
            used = set()
            for i in range(len(a)):
                for j in range(len(b)):
                    for k in range(len(c)):
                        free.append((i, j, k, str(i) + '-' + str(j) + '-' + str(k)))
        i, j, k, key = random.choice(free)
        used.add(key)
        data[kind] = sorted(used)
        _save(data)
    return a[i] + ' ' + b[j] + ' ' + c[k]
